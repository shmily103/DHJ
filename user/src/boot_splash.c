/*
 * BootSplash_Show
 * ------------------------------------------------------------
 * 这是系统开机时的第一个视觉界面，主要用于在设备还没进入正式
 * 工作状态前给用户提供稳定的品牌和功能提示。
 *
 * 画面命令被提交到 ST7789 帧队列后，本函数立即返回；像素数据由
 * 主循环反复调用 ST7789_Task()，通过有限长度 DMA 分段传输。这样
 * 避免启动阶段等待整屏绘制完成而卡住控制和输入处理。
 *
 * 展示计时在画面帧传输完成后由 BootSplash_IsActive() 启动，避免
 * DMA 传输时间挤占实际可见的启动画面时长。
 */
void BootSplash_Show(void)
{
  const char *subtitle = "4串超级电容";

  g_splash_active = 1U;
  g_splash_timer_started = 0U;
  g_splash_deadline_ms = 0U;

  ST7789_BeginFrame(BOOT_SPLASH_BACKGROUND);

  ST7789_DrawCenteredString(20U, 59U, ST7789_WIDTH - 40U, subtitle,
                            BOOT_SPLASH_SUBTITLE, BOOT_SPLASH_BACKGROUND);

  ST7789_DrawBitmap48(88U, 112U, g_title_dot, BOOT_SPLASH_TITLE, BOOT_SPLASH_BACKGROUND);
  ST7789_DrawBitmap48(136U, 112U, g_title_weld, BOOT_SPLASH_TITLE, BOOT_SPLASH_BACKGROUND);
  ST7789_DrawBitmap48(184U, 112U, g_title_machine, BOOT_SPLASH_TITLE, BOOT_SPLASH_BACKGROUND);
  ST7789_EndFrame();
}

/* 在完整展示指定时长后通知主界面可以开始绘制。 */
uint8_t BootSplash_IsActive(void)
{
  uint32_t now = 0U;

  if (g_splash_active == 0U)
  {
    return 0U;
  }

  if (g_splash_timer_started == 0U)
  {
    if (ST7789_FrameIsBusy() != 0U)
    {
      return 1U;
    }

    g_splash_deadline_ms = HAL_GetTick() + BOOT_SPLASH_DURATION_MS;
    g_splash_timer_started = 1U;
  }

  now = HAL_GetTick();
  if ((int32_t)(now - g_splash_deadline_ms) >= 0)
  {
    g_splash_active = 0U;
    return 0U;
  }

  return 1U;
}

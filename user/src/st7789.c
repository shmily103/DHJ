/*
 * ST7789_AppendRectCommand
 * ------------------------------------------------------------
 * 把矩形填充请求追加进入当前帧命令队列。
 *
 * 这里不直接执行屏幕写入，而是把绘制任务先缓存到 g_frame_commands[]
 * 中，待整个帧完成后再统一刷新到 LCD。
 *
 * 这样做的好处是：
 *   - 可合并多个绘制命令，减少 SPI 事务开销；
 *   - 可在一帧里一次性完成多块区域绘制；
 *   - 能降低 CPU 对 LCD 的频繁打断，提高系统实时性。
 */
static void ST7789_AppendRectCommand(uint16_t x, uint16_t y, uint16_t w, uint16_t h,
                                    uint16_t color)
{
  ST7789_FrameCommand_t *command = NULL;

  if (g_frame_command_count >= ST7789_FRAME_COMMAND_CAPACITY)
  {
    Error_Handler();
    return;
  }

  command = &g_frame_commands[g_frame_command_count++];
  command->type = ST7789_FRAME_COMMAND_RECT;
  command->x = x;
  command->y = y;
  command->data.rect.w = w;
  command->data.rect.h = h;
  command->data.rect.color = color;
}

/*
 * ST7789_AppendTextCommand
 * ------------------------------------------------------------
 * 将文本绘制请求加入当前帧缓存。
 *
 * 它会顺序记录：
 *   - 文字的位置；
 *   - 前景/背景色；
 *   - 缩放尺寸；
 *   - 字符串内容。
 *
 * 不在此函数中直接输出字模，而是把文本作为一条“绘图命令”保存，
 * 等待 ST7789_Task() 或 EndFrame 流程统一渲染。这样处理后，多个文
 * 本和图形对象可以被按顺序组合成一帧，而非逐个立刻写入屏幕。
 */
static void ST7789_AppendTextCommand(uint16_t x, uint16_t y, const char *str,
                                    uint16_t fg_color, uint16_t bg_color,
                                    uint8_t scale)
{
  ST7789_FrameCommand_t *command = NULL;
  size_t text_length = 0U;

  if (g_frame_command_count >= ST7789_FRAME_COMMAND_CAPACITY)
  {
    Error_Handler();
  }

  text_length = strlen(str);
  if (text_length >= ST7789_FRAME_TEXT_CAPACITY)
  {
    Error_Handler();
    return;
  }

  command = &g_frame_commands[g_frame_command_count++];
  command->type = ST7789_FRAME_COMMAND_TEXT;
  command->x = x;
  command->y = y;
  command->data.text.fg_color = fg_color;
  command->data.text.bg_color = bg_color;
  command->data.text.scale = scale;
  memcpy(command->data.text.text, str, text_length + 1U);
}


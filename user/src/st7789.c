/*
 * ST7789_TransmitDma
 * ------------------------------------------------------------
 * 通过 SPI DMA 发送一段原始像素数据。
 *
 * 它的关键职责是：
 *   - 使用 HAL_SPI_Transmit_DMA() 触发真正的数据传输；
 *   - 轮询等待 SPI 结束；
 *   - 超时后中止传输并调用 Error_Handler()；
 *   - 若底层错误码不为 NONE，则立刻报错。
 *
 * 这一层封装的意义在于，将显示控制器的 DMA 访问封装起来，避免
 * 其余绘图逻辑需要了解 SPI 状态机和错误处理细节。
 */
static void ST7789_TransmitDma(uint8_t *data, uint16_t len)
{
  uint32_t start_tick = HAL_GetTick();

  if (HAL_SPI_Transmit_DMA(&hspi1, data, len) != HAL_OK)
  {
    Error_Handler();
  }

  while (HAL_SPI_GetState(&hspi1) == HAL_SPI_STATE_BUSY_TX)
  {
    if ((uint32_t)(HAL_GetTick() - start_tick) >= 100U)
    {
      (void)HAL_SPI_Abort(&hspi1);
      Error_Handler();
    }
  }

  if (hspi1.ErrorCode != HAL_SPI_ERROR_NONE)
  {
    Error_Handler();
  }
}

static void ST7789_StartFrameDma(uint8_t *data, uint16_t len)
{
  if (HAL_SPI_Transmit_DMA(&hspi1, data, len) != HAL_OK)
  {
    Error_Handler();
  }
}

